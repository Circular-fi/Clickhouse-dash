const STATE_KEY = "mcp.state";

// The state of MCP decides what the panel shows. A page restored from the back/forward cache is as old as the visit: it loads again.
async function load() {
  const state = dom.byId("mcpState");
  const req = util.latest(STATE_KEY);
  mcpOverview.hide();
  uiState.loading(state, { label: "Loading the MCP state\u2026" });
  let meta;
  try {
    meta = await api.getMcpMeta({ signal: req.signal });
  } catch (error) {
    if (req.isCurrent()) uiState.error(state, { title: "Could not load the MCP state", body: util.errorText(error), retry: () => load() });
    return;
  }
  if (!req.isCurrent()) return;
  state.removeAttribute("aria-busy");
  if (!meta.enabled) {
    mcpView.renderDisabled(state);
    return;
  }
  state.replaceChildren();
  mcpOverview.show(dom.byId("mcpOverview"), { meta });
}

async function start() {
  header.setPageSelectorValue("mcp");
  header.init();
  shell.edgeCues(dom.byId("mcpTabs"));
  window.addEventListener("pageshow", (event) => { if (event.persisted) void load(); });
  await load();
}

