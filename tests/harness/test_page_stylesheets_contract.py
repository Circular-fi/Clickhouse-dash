import importlib.util
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
PAGES = ["query", "explorer", "traces", "logs", "metrics"]


def read(rel: str) -> str:
    return (ROOT / rel).read_text(encoding="utf-8")


def load_builder():
    spec = importlib.util.spec_from_file_location("build_page_css", ROOT / "tools" / "build_page_css.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def test_each_page_shell_loads_its_own_generated_stylesheet():
    for page in PAGES:
        html = read(f"src/static/{page}.html")
        assert f'var cssHref = window.__chdashUrl("static/style.{page}.css")' in html, page
        assert 'window.__chdashUrl("static/style.css")' not in html, page
        assert "document.write('<link rel=\"stylesheet\" href=\"' + cssHref + '\">');" in html, page


def test_generated_page_stylesheets_are_current():
    builder = load_builder()
    outputs = builder.build()
    assert sorted(path.name for path in outputs) == sorted(f"style.{page}.css" for page in PAGES)
    for path, text in outputs.items():
        assert path.is_file(), f"{path.name} missing: run python3 tools/build_page_css.py"
        assert path.read_text(encoding="utf-8") == text, f"{path.name} is stale: run python3 tools/build_page_css.py"


def test_page_stylesheets_keep_style_css_order_and_drop_only_unmatchable_rules():
    builder = load_builder()
    source = read("src/static/style.css")
    for page in PAGES:
        header, css = read(f"src/static/style.{page}.css").split("\n", 1)
        assert header.startswith("/* Generated by tools/build_page_css.py"), page
        # Every kept rule is copied verbatim and in the original order.
        position = 0
        for prelude in re.findall(r"^([^{}@\s][^{}]*?) \{", css, flags=re.M)[:400]:
            found = re.compile(re.escape(prelude) + r"\s*\{").search(source, position)
            assert found, (page, prelude)
            position = found.start()
        assert len(css) < len(source), page
    corpus = builder.Corpus(builder.page_corpus("traces"))
    # Names assembled at run time count as present ("chdash-trace-tab-" + tab).
    assert corpus.has("chdash-trace-tab-services")
    # Lookups of an id another page owns do not keep that page's rules.
    assert not builder.Corpus(builder.page_corpus("logs")).has("explorerDetailTabs")
    assert builder.selector_can_match(".traceX:not(.queryOnlyName)", corpus) == corpus.has("traceX")


def test_query_and_explorer_skip_the_modules_they_never_run():
    builder = load_builder()
    app = read("src/static/app.js")
    assert "const skipped = new Set(PAGE_SKIPPED_MODULES[document.body?.dataset.page] || []);" in app
    assert "if (skipped.has(f)) continue;" in app
    query = builder.page_modules("query")
    explorer = builder.page_modules("explorer")
    assert {"app_explorer.js", "app_run.js", "app_autocomplete.js", "app_analysis.js"} <= set(query)
    assert "app_explorer_graph.js" not in query and "app_explorer_treemap.js" not in query
    assert {"app_explorer.js", "app_explorer_graph.js", "app_explorer_treemap.js", "app_results.js", "app_highlight.js"} <= set(explorer)
    for name in ["app_autocomplete.js", "app_run.js", "app_analysis.js", "app_pipeline_viewer.js", "app_trace_viewer.js", "app_download.js", "app_export.js"]:
        assert name not in explorer, name
