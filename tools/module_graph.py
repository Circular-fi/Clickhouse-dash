"""The module graph of src/static: ES modules, their imports, and the pages built from them.

Every script of src/static/app_*.js is an ES module. A page is its entry (src/static/modules.json, pages.<page>.entry:
app_page_<page>.js): the modules it imports, and theirs in turn, are the page. The browser loads them in dependency
order. Nothing else lists them. What modules.json adds is the lazy groups of a page: modules that load on first use
through loader.loadGroup(name) (app_loader.js), such as the query library, the chart engine or a WebAssembly adapter.

  closure(entry)      the modules the entry imports, directly and not, dependencies first, the entry last
  page_files(page)    closure of the page's entry: what the shell preloads
  page_modules(page)  page_files plus the lazy files and their closures: what the page can run (the stylesheet filter)
  rewrite(text, versions)
                      the module with every import specifier carrying ?v=<hash of the imported module> (tools/stage_static.py)
  with_handle(entry, text)
                      the entry with its generated handle region: `import * as h_x` of every module of the page and one
                      loader.expose([...]) call, so window.ChDash is complete when the entry has run, before the load event

`python3 tools/module_graph.py` (also run by tools/build_page_css.py --check and by the harness) fails when

  - a module imports something that is not a sibling module by its exact name (`./app_x.js`),
  - the imports have a cycle (the content hash of a module includes the hashes of its imports, so a cycle has none),
  - a script is on no page (not in a closure of an entry or a lazy group, and not the Worker script),
  - a lazy module is also imported by a module of the page that loads it lazily (it would not be lazy),
  - a module reads the window.ChDash handle (only app_loader.js writes it: the tests and the console read it).
"""
from __future__ import annotations

import json
import re
import sys
from functools import lru_cache
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
STATIC = ROOT / "src" / "static"
MANIFEST = STATIC / "modules.json"
# Shipped and listed on no page: the module Worker of the WebAssembly kernels (app_wasm.js starts it by name).
WORKER = "app_wasm_worker.js"
# The one module that writes window.ChDash.
HANDLE_WRITER = "app_loader.js"

# `import { a } from "./x.js";`, `import "./x.js";`, `export { a } from "./x.js";` at the start of a line.
IMPORT = re.compile(r"""^(?:import|export)\b(?:[^"'`;]*?\bfrom\s*)?\s*["']([^"']+)["']\s*;""", re.M | re.S)
EXACT = re.compile(r"^\./(app_[a-z0-9_]+\.js)$")
DYNAMIC = re.compile(r"\bimport\s*\(")
HANDLE = re.compile(r"(?:window|self|globalThis)\.ChDash\b|\bChDash\??\.[A-Za-z_]")


def manifest() -> dict:
    return json.loads(MANIFEST.read_text(encoding="utf-8"))


def strip_comments(text: str) -> str:
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    return re.sub(r"(^|[\s;{}()])//[^\n]*", r"\1", text)


@lru_cache(maxsize=None)
def source(name: str) -> str:
    return (STATIC / name).read_text(encoding="utf-8")


HANDLE_START = "// handle:start - generated by tools/build_page_css.py (tools/module_graph.py): the namespace of every module of the page, for window.ChDash (app_loader.js). Do not edit.\n"
HANDLE_END = "// handle:end\n"
HANDLE_REGION = re.compile(re.escape(HANDLE_START.split(" - ")[0]) + r".*?" + re.escape(HANDLE_END) + r"\n?", re.S)


def strip_handle(text: str) -> str:
    return HANDLE_REGION.sub("", text)


def specifiers(text: str) -> list[str]:
    """The module specifiers of the static imports (and re-exports) of a module."""
    return IMPORT.findall(strip_comments(strip_handle(text)))


def static_imports(name: str, text: str | None = None) -> list[str]:
    """The sibling modules `name` imports, in the order of its import statements, once each."""
    out: list[str] = []
    for spec in specifiers(source(name) if text is None else text):
        match = EXACT.match(spec)
        if match and match.group(1) not in out:
            out.append(match.group(1))
    return out


def closure(entry: str, imports=static_imports) -> list[str]:
    """The entry and everything it imports, dependencies first (the order the browser evaluates them in)."""
    out: list[str] = []
    seen: set[str] = set()

    def visit(name: str) -> None:
        if name in seen:
            return
        seen.add(name)
        for dep in imports(name):
            visit(dep)
        out.append(name)

    visit(entry)
    return out


def page_files(page: str, data: dict | None = None) -> list[str]:
    return closure((data or manifest())["pages"][page]["entry"])


def lazy_files(page: str, data: dict | None = None) -> list[str]:
    groups = (data or manifest())["pages"][page].get("lazy") or {}
    out: list[str] = []
    for files in groups.values():
        for name in files:
            if name not in out:
                out.append(name)
    return out


def page_modules(page: str, data: dict | None = None) -> list[str]:
    """Every module the page can run: its closure, the lazy files and what they import."""
    data = data or manifest()
    out = page_files(page, data)
    for name in lazy_files(page, data):
        for dep in closure(name):
            if dep not in out:
                out.append(dep)
    return out


def cycle_in(graph: dict[str, list[str]]) -> list[str] | None:
    state: dict[str, int] = {}
    stack: list[str] = []

    def visit(name: str) -> list[str] | None:
        state[name] = 1
        stack.append(name)
        for target in graph.get(name, []):
            if state.get(target) == 1:
                return [*stack[stack.index(target) :], target]
            if target not in state and (found := visit(target)):
                return found
        stack.pop()
        state[name] = 2
        return None

    for name in graph:
        if name not in state and (found := visit(name)):
            return found
    return None


def graph() -> dict[str, list[str]]:
    return {path.name: static_imports(path.name) for path in sorted(STATIC.glob("app_*.js"))}


def rewrite(text: str, versions: dict[str, str]) -> str:
    """`./app_x.js` becomes `./app_x.js?v=<versions[app_x.js]>` in every static import of the module."""

    def one(match: re.Match) -> str:
        spec = match.group(1)
        found = EXACT.match(spec)
        if not found or found.group(1) not in versions:
            return match.group(0)
        return match.group(0).replace(f'"{spec}"', f'"{spec}?v={versions[found.group(1)]}"').replace(f"'{spec}'", f"'{spec}?v={versions[found.group(1)]}'")

    return IMPORT.sub(one, text)


def handle_region(entry: str) -> str:
    aliases = [(name, "h_" + name[len("app_") : -len(".js")]) for name in closure(entry) if name != entry]
    lines = [HANDLE_START] + [f'import * as {alias} from "./{name}";\n' for name, alias in aliases]
    lines.append("h_loader.loader.expose([\n" + "".join(f"  {alias},\n" for _, alias in aliases) + "]);\n")
    lines.append(HANDLE_END)
    return "".join(lines) + "\n"


def with_handle(entry: str, text: str) -> str:
    """The entry text with its handle region, placed before the boot() call that ends it."""
    text = strip_handle(text)
    match = re.search(r"^boot\(", text, re.M)
    assert match, f"{entry} has no boot() call"
    return text[: match.start()] + handle_region(entry) + text[match.start() :]


def entries() -> list[str]:
    return [page["entry"] for page in manifest()["pages"].values()]


def problems() -> list[str]:
    data = manifest()
    out: list[str] = []
    shipped = {path.name for path in STATIC.glob("app_*.js")}
    modules = graph()
    # 1. imports are exact sibling names
    for name in sorted(shipped):
        text = source(name)
        for spec in specifiers(text):
            match = EXACT.match(spec)
            if not match:
                out.append(f"{name} imports {spec!r}: write the sibling module as ./app_<name>.js")
            elif match.group(1) not in shipped:
                out.append(f"{name} imports {spec}, which is not there")
        # a dynamic import goes through loader.loadGroup (app_loader.js) or the Worker; no other module writes one
        if name not in (HANDLE_WRITER, WORKER) and DYNAMIC.search(strip_comments(text)):
            out.append(f"{name} calls import(): lazy modules load through loader.loadGroup (modules.json lazy groups)")
        if name != HANDLE_WRITER and HANDLE.search(strip_comments(text)):
            out.append(f"{name} reads window.ChDash: import what it needs (only app_loader.js writes the handle)")
    # a generated handle region is part of every entry
    for entry in entries():
        if entry in shipped and source(entry) != with_handle(entry, source(entry)):
            out.append(f"{entry}: the handle region is stale (run python3 tools/build_page_css.py)")
    # 2. no cycle
    if (cycle := cycle_in(modules)) is not None:
        out.append("import cycle: " + " -> ".join(cycle))
    # 3. every page: entry exists, lazy files exist
    reached: set[str] = {WORKER}
    for page, entry in data["pages"].items():
        if entry["entry"] not in shipped:
            out.append(f"{page}: the entry {entry['entry']} is missing")
            continue
        files = set(page_files(page, data))
        reached |= set(page_modules(page, data))
        for group, names in (entry.get("lazy") or {}).items():
            for name in names:
                if name not in shipped:
                    out.append(f"{page}: lazy group {group} names a missing module: {name}")
                elif name in files:
                    out.append(f"{page}: {name} is lazy (group {group}) but the page imports it")
    for name in sorted(shipped - reached):
        out.append(f"{name} is on no page")
    return out


def main() -> int:
    found = problems()
    for line in found:
        print(line, file=sys.stderr)
    return 1 if found else 0


if __name__ == "__main__":
    sys.exit(main())
